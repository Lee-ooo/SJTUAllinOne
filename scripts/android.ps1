param(
    [Parameter(Position = 0, Mandatory = $true)]
    [ValidateSet('gradle', 'adb', 'emulator', 'sdkmanager', 'avdmanager')]
    [string]$Tool,
    [Parameter(Position = 1, ValueFromRemainingArguments = $true)]
    [string[]]$ToolArgs
)

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path $PSScriptRoot -Parent
$localRoot = Join-Path $repoRoot '.local'
$sdkRoot = Join-Path $localRoot 'tools/android-sdk'
$tempRoot = Join-Path $localRoot 'tmp'
$javaHome = Join-Path $localRoot 'java-home'
New-Item -ItemType Directory -Force -Path $tempRoot, $javaHome | Out-Null
$environment = @{
    JAVA_HOME = Join-Path $localRoot 'tools/jdk/jdk-17.0.20.1+1'
    ANDROID_HOME = $sdkRoot
    ANDROID_SDK_ROOT = $sdkRoot
    ANDROID_USER_HOME = Join-Path $localRoot 'android-user'
    ANDROID_EMULATOR_HOME = Join-Path $localRoot 'android-user'
    ANDROID_AVD_HOME = Join-Path $localRoot 'android-user/avd'
    GRADLE_USER_HOME = Join-Path $localRoot 'gradle-home'
    TEMP = $tempRoot
    TMP = $tempRoot
    JAVA_TOOL_OPTIONS = ($env:JAVA_TOOL_OPTIONS + ' -Duser.home="' + $javaHome + '" -Djava.io.tmpdir="' + $tempRoot + '"').Trim()
}
$executables = @{
    gradle = Join-Path $localRoot 'tools/gradle/gradle-8.13/bin/gradle.bat'
    adb = Join-Path $sdkRoot 'platform-tools/adb.exe'
    emulator = Join-Path $sdkRoot 'emulator/emulator.exe'
    sdkmanager = Join-Path $sdkRoot 'cmdline-tools/latest/bin/sdkmanager.bat'
    avdmanager = Join-Path $sdkRoot 'cmdline-tools/latest/bin/avdmanager.bat'
}
$savedEnvironment = @{}
if (!(Test-Path -LiteralPath $executables[$Tool] -PathType Leaf)) {
    throw "Project tool missing: $($executables[$Tool]). Copy the complete .local directory with the project."
}
# The emulator resolves path.rel against ANDROID_EMULATOR_HOME.
# hardware-qemu.ini is generated by the emulator and may contain runtime absolute paths.
$avdRoot = $environment.ANDROID_AVD_HOME
foreach ($registration in Get-ChildItem -LiteralPath $avdRoot -Filter '*.ini' -File) {
    $lines = @(Get-Content -LiteralPath $registration.FullName)
    $relativePath = 'path.rel=avd/' + $registration.BaseName + '.avd'
    $portableLines = @($lines | Where-Object { $_ -notmatch '^path(?:\.rel)?=' }) + $relativePath
    if (($lines -join "`n") -ne ($portableLines -join "`n")) {
        Set-Content -LiteralPath $registration.FullName -Value $portableLines -Encoding ascii
    }
}
try {
    foreach ($name in $environment.Keys) {
        $savedEnvironment[$name] = [Environment]::GetEnvironmentVariable($name, 'Process')
        [Environment]::SetEnvironmentVariable($name, $environment[$name], 'Process')
    }
    Push-Location $repoRoot
    try {
        & $executables[$Tool] @ToolArgs
        if ($LASTEXITCODE -ne 0) { throw "$Tool failed with exit code $LASTEXITCODE" }
    } finally { Pop-Location }
} finally {
    foreach ($name in $savedEnvironment.Keys) {
        if ($null -eq $savedEnvironment[$name]) {
            Remove-Item -LiteralPath "Env:$name" -ErrorAction SilentlyContinue
        } else {
            [Environment]::SetEnvironmentVariable($name, $savedEnvironment[$name], 'Process')
        }
    }
}
